exports.askTUFY = async (req, res) => {
  try {
    const { question, context = '' } = req.body;
    if (!question) return res.status(400).json({ success: false, message: 'Question required' });

    let answer;

    if (process.env.OPENAI_API_KEY) {
      const OpenAI = require('openai');
      const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });
      const completion = await openai.chat.completions.create({
        model: 'gpt-3.5-turbo',
        messages: [
          { role: 'system', content: 'You are TUFY, an expert CS interview preparation assistant. Explain concepts clearly with examples in Java. Be concise but thorough. Use markdown formatting.' },
          { role: 'user', content: context ? `Context: ${context}\n\nQuestion: ${question}` : question }
        ],
        max_tokens: 800,
      });
      answer = completion.choices[0].message.content;
    } else {
      answer = getMockResponse('ask', question);
    }

    res.json({ success: true, answer });
  } catch (err) {
    res.status(500).json({ success: false, message: err.message });
  }
};

