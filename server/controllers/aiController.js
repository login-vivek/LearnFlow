exports.getSuggestions = async (req, res) => {
  try {
    const userId = req.user._id;

    // Gather context: last 14 days progress + active plan
    const fourteenDaysAgo = new Date();
    fourteenDaysAgo.setDate(fourteenDaysAgo.getDate() - 14);
    const fromStr = fourteenDaysAgo.toISOString().split('T')[0];

    const [recentProgress, activePlan] = await Promise.all([
      Progress.find({ user: userId, date: { $gte: fromStr } }).sort({ date: -1 }),
      StudyPlan.findOne({ user: userId, active: true }),
    ]);

    // Build topic frequency map from progress logs
    const topicFreq = {};
    recentProgress.forEach(p => {
      (p.topics || []).forEach(t => { topicFreq[t] = (topicFreq[t] || 0) + 1; });
    });

    // Topics skipped or pending from active plan (past due, not completed)
    const todayStr = new Date().toISOString().split('T')[0];
    const pendingTopics  = [];
    const skippedTopics  = [];

    if (activePlan) {
      activePlan.tasks.forEach(task => {
        if (!task.completed) {
          if (task.date < todayStr) skippedTopics.push(task.topic);
          else if (task.date === todayStr) pendingTopics.push(task.topic);
        }
      });
    }

    // Topics studied < 2 times in last 14 days — considered weak
    const allPlanTopics = activePlan
      ? [...new Set(activePlan.tasks.map(t => t.topic))]
      : ['Dynamic Programming', 'Graphs - BFS/DFS', 'Trees - BFS/DFS', 'Binary Search', 'Backtracking'];

    const weakTopics = allPlanTopics.filter(t => (topicFreq[t] || 0) < 2);

    // Use OpenAI if available, else smart mock
    if (process.env.OPENAI_API_KEY) {
      const OpenAI = require('openai');
      const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });

      const context = `
User's recent study data (last 14 days):
- Topics studied with frequency: ${JSON.stringify(topicFreq)}
- Skipped/overdue tasks: ${[...new Set(skippedTopics)].slice(0, 6).join(', ') || 'none'}
- Pending today: ${[...new Set(pendingTopics)].slice(0, 4).join(', ') || 'none'}
- Weak topics (studied < 2 times): ${weakTopics.slice(0, 6).join(', ') || 'none'}
- Target company: ${activePlan?.targetCompany || 'general placement'}
- Deadline: ${activePlan?.deadline || 'not set'}
      `.trim();

      const completion = await openai.chat.completions.create({
        model: 'gpt-3.5-turbo',
        messages: [
          {
            role: 'system',
            content: `You are an expert placement preparation coach. Analyse the student's study data and return EXACTLY 3 to 4 topic suggestions as a JSON array.
Each suggestion must have: topic (string), priority ("high"|"medium"|"low"), reason (1 sentence why this needs focus), tip (1 actionable sentence on how to study it).
Return ONLY valid JSON array, no markdown, no explanation.`,
          },
          { role: 'user', content: context },
        ],
        max_tokens: 500,
        temperature: 0.4,
      });

      try {
        const suggestions = JSON.parse(completion.choices[0].message.content);
        return res.json({ success: true, suggestions });
      } catch {
        // OpenAI returned malformed JSON — fall through to mock
      }
    }

    // Smart mock fallback
    const suggestions = getMockSuggestions(weakTopics, [...new Set(pendingTopics)], [...new Set(skippedTopics)]);

    // Always return at least 3 suggestions — pad with defaults if needed
    const defaults = [
      { topic: 'Dynamic Programming', priority: 'high', reason: 'DP is the highest-frequency hard topic across all product companies.', tip: 'Start with 1D DP problems — Climbing Stairs, House Robber, and Fibonacci with memoization.' },
      { topic: 'Graphs - BFS/DFS',    priority: 'high', reason: 'Graph traversal problems appear in every SDE-1 interview round.', tip: 'Implement BFS and DFS from scratch. Solve Number of Islands on LeetCode.' },
      { topic: 'Binary Search',       priority: 'medium', reason: 'Binary search variants are common in online assessments.', tip: 'Go beyond basic search — practice on rotated arrays and on the answer space.' },
      { topic: 'SQL - Joins & Subqueries', priority: 'medium', reason: 'SQL is tested in TCS, Infosys and every data-related role.', tip: 'Practice INNER JOIN, LEFT JOIN, and nested subqueries on HackerRank SQL track.' },
    ];

    while (suggestions.length < 3) {
      const def = defaults[suggestions.length];
      if (def && !suggestions.find(s => s.topic === def.topic)) suggestions.push(def);
      else break;
    }

    res.json({ success: true, suggestions: suggestions.slice(0, 4) });
  } catch (err) {
    res.status(500).json({ success: false, message: err.message });
  }
};
